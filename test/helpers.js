// Shared test helpers. Every store is a scratch folder under the OS temp
// folder; every run sets FORGE_DEPLOY=0 (no network), and HOME and
// XDG_CONFIG_HOME are scratch folders, so no user setting (and no
// secretCommand) is ever read from the real home folder.
const assert = require("node:assert");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { spawnSync, spawn } = require("node:child_process");

const ENGINE = path.resolve(__dirname, "..");
const FORGE = path.join(ENGINE, "bin", "forge");

// FORGE_TEST_KEEP_GOING=1 runs every check and reports each failure (for
// showing a whole file's failing checks at once); by default the first
// failure stops the file.
let passed = 0;
let failed = 0;
async function check(name, fn) {
  try {
    await fn();
  } catch (e) {
    console.log("  not ok - " + name);
    if (!process.env.FORGE_TEST_KEEP_GOING) throw e;
    failed++;
    console.log("    " + String(e && e.message).split("\n").slice(0, 4).join("\n    "));
    return;
  }
  passed++;
  console.log("  ok - " + name);
}
const done = () => {
  console.log(passed + " checks passed" + (failed ? ", " + failed + " failed" : ""));
  if (failed) process.exitCode = 1;
};

// Every scratch folder a test makes is removed when the test process ends,
// pass or fail.
const made = [];
process.on("exit", () => { for (const d of made) fs.rmSync(d, { recursive: true, force: true }); });
function tmp(prefix) {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), "forge-test-" + prefix + "-"));
  made.push(d);
  return d;
}

// Every child (bin/forge, git) gets a home folder this test run owns, and git
// reads no global or system configuration (no owner identity, hooks or
// aliases); the author is explicit.
const HOME = tmp("home");
const GIT_ENV = {
  HOME, XDG_CONFIG_HOME: path.join(HOME, ".config"), GIT_CONFIG_GLOBAL: "/dev/null", GIT_CONFIG_NOSYSTEM: "1",
  GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@example.invalid", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@example.invalid",
};

// The children's temp folder (where forge makes its temporary worktrees) is one
// this test run owns too, so a killed command's leftovers go with it.
const CHILD_TMP = tmp("childtmp");
function env(store, extra = {}) {
  const base = { ...process.env };
  delete base.FORGE_LOCK_HELD; // never inherit a lock claim from the shell running the tests
  delete base.FORGE_LOCK_FD;
  return { ...base, ...GIT_ENV, TMPDIR: CHILD_TMP, FORGE_DEPLOY: "0", FORGE_WORKSPACE: store, ...extra };
}

function run(store, args, opts = {}) {
  const r = spawnSync(process.execPath, [FORGE, ...args], { cwd: opts.cwd || os.tmpdir(), env: env(store, opts.env), encoding: "utf8" });
  return { status: r.status, out: r.stdout, err: r.stderr, all: r.stdout + r.stderr };
}

function runAsync(store, args, opts = {}) {
  return new Promise((resolve) => {
    const c = spawn(process.execPath, [FORGE, ...args], { cwd: opts.cwd || os.tmpdir(), env: env(store, opts.env) });
    let out = "";
    let err = "";
    c.stdout.on("data", (d) => (out += d));
    c.stderr.on("data", (d) => (err += d));
    c.on("close", (status) => resolve({ status, out, err, all: out + err }));
  });
}

function git(dir, args) {
  const r = spawnSync("git", args, { cwd: dir, encoding: "utf8", env: { ...process.env, ...GIT_ENV } });
  if (r.status !== 0) throw new Error("git " + args.join(" ") + ": " + r.stderr);
  return r.stdout.trim();
}

const CONFIG = {
  baseUrl: "https://pub.example.org",
  privateBaseUrl: "http://127.0.0.1:8080/forge",
  host: { kind: "cloudflare-pages", project: "test-project", accountId: "test-account", tokenSecret: "FORGE_TEST_TOKEN_NOT_SET" },
  brand: { name: "Acme", wordmarkFile: null, indexTagHtml: "Acme &middot; Internal", historyFooterHtml: "Generated by the test publisher." },
};

// A configured, committed store made through the real `forge init`.
function makeStore(config = CONFIG) {
  const dir = tmp("store");
  const store = path.join(dir, "store");
  const r = run(store, ["init", store]);
  assert.strictEqual(r.status, 0, r.all);
  fs.writeFileSync(path.join(store, "config.json"), JSON.stringify(config, null, 2) + "\n");
  git(store, ["commit", "-qam", "configure"]);
  return store;
}

// A source folder outside any store, with helpers to write pages into it.
function makeSrc() {
  const dir = tmp("src");
  return {
    dir,
    page(rel, title, body) {
      const p = path.join(dir, rel);
      fs.mkdirSync(path.dirname(p), { recursive: true });
      fs.writeFileSync(p, "<html><head><title>" + title + "</title></head><body>" + body + "</body></html>");
      return p;
    },
    file(rel, content) {
      const p = path.join(dir, rel);
      fs.mkdirSync(path.dirname(p), { recursive: true });
      fs.writeFileSync(p, content);
      return p;
    },
  };
}

const manifest = (store) => JSON.parse(fs.readFileSync(path.join(store, "manifest.json"), "utf8"));

// Every file in a tree, with its bytes' hash: the identity of a store's state.
function treeState(dir) {
  const crypto = require("node:crypto");
  const out = {};
  const walk = (abs, rel) => {
    if (!fs.existsSync(abs)) return;
    for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
      if (!rel && e.name === ".git") continue;
      const p = path.join(abs, e.name);
      const r = rel ? rel + "/" + e.name : e.name;
      if (e.isDirectory()) walk(p, r);
      else out[r] = crypto.createHash("sha256").update(fs.readFileSync(p)).digest("hex");
    }
  };
  walk(dir, "");
  return out;
}

// Start bin/forge in the background; waitFor resolves when its output matches
// (and rejects after 20 s, so a pause point that never comes fails the test).
function start(store, args, opts = {}) {
  const c = spawn(process.execPath, [FORGE, ...args], { cwd: opts.cwd || os.tmpdir(), env: env(store, opts.env) });
  let all = "";
  let out = "";
  const waiters = [];
  const feed = (d) => { all += d; for (const w of waiters) if (w.re.test(all)) w.ok(); };
  c.stdout.on("data", (d) => { out += d; feed(d); });
  c.stderr.on("data", feed);
  let err = "";
  c.stderr.on("data", (d) => { err += d; });
  const closed = new Promise((r) => c.on("close", (status) => r({ status, all, out, err })));
  return {
    c, closed,
    waitFor: (re) => new Promise((ok, bad) => {
      if (re.test(all)) return ok();
      const t = setTimeout(() => bad(new Error("timed out waiting for " + re + "; output so far:\n" + all)), 20000);
      waiters.push({ re, ok: () => { clearTimeout(t); ok(); } });
    }),
    // The process forge started to run the command under the lock.
    holder: () => Number(require("node:child_process").execFileSync("pgrep", ["-P", String(c.pid)], { encoding: "utf8" }).trim()),
  };
}

// Two clones of one store, as two machines, sharing a bare remote.
function twoMachines(makeA = makeStore) {
  const a = makeA();
  const bare = path.join(tmp("remote"), "store.git");
  git(path.dirname(bare), ["init", "-q", "--bare", bare]);
  git(bare, ["symbolic-ref", "HEAD", "refs/heads/main"]); // the store's branch, whatever git's default
  git(a, ["remote", "add", "origin", bare]);
  git(a, ["push", "-q", "-u", "origin", "HEAD"]);
  const b = path.join(tmp("clone"), "store");
  git(path.dirname(b), ["clone", "-q", bare, b]);
  return { a, b, bare };
}

module.exports = { start, twoMachines, HOME, ENGINE, FORGE, check, done, tmp, run, runAsync, git, env, makeStore, makeSrc, manifest, treeState, CONFIG, GIT_ENV };
