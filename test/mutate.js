const only = process.argv.slice(2);
const list = only.length ? MUTANTS.filter((m) => only.includes(m.id)) : MUTANTS;
if (only.length && list.length !== only.length) {
  console.error("unknown mutant id; known: " + MUTANTS.map((m) => m.id).join(", "));
  process.exit(1);
}

// The scratch copy goes on any exit, a stopped run included.
let copy = null;
const cleanup = () => { if (copy) fs.rmSync(copy, { recursive: true, force: true }); };
process.on("exit", cleanup);
for (const sig of ["SIGINT", "SIGTERM", "SIGHUP"]) process.on(sig, () => process.exit(130));

let survived = 0;
for (const m of list) {
  copy = fs.mkdtempSync(path.join(os.tmpdir(), "forge-mutant-" + m.id + "-"));
  fs.cpSync(ENGINE, copy, { recursive: true, filter: (src) => !/[/\\](\.git|workspace)$/.test(src) });
  const file = path.join(copy, m.file);
  const text = fs.readFileSync(file, "utf8");
  const n = text.split(m.find).length - 1;
  if (n !== 1) {
    console.log("BROKEN MUTANT " + m.id + ": the guard text appears " + n + " times in " + m.file);
    survived++;
    fs.rmSync(copy, { recursive: true, force: true });
    continue;
  }
  fs.writeFileSync(file, text.split(m.find).join(m.replace));
  // The test's scratch stores go inside the copy, so they are removed with it.
  const scratch = path.join(copy, ".tmp");
  fs.mkdirSync(scratch);
  const run = m.test.endsWith(".py") ? "python3" : process.execPath;
  const r = spawnSync(run, [path.join(copy, "test", m.test)], { encoding: "utf8", timeout: 300000, env: { ...process.env, FORGE_DEPLOY: "0", TMPDIR: scratch } });
  const out = (r.stdout || "") + (r.stderr || "");
  const failed = (out.match(/^ {2}not ok - (.*)$/m) || [])[1];
  const after = out.split(/^ {2}not ok - .*$/m)[1] || "";
  const errLines = after.split("\n").filter((l) => l.trim() && !/^\s+at /.test(l) && !/^\s*(code|operator|diff|generatedMessage):/.test(l)).slice(0, 6);
  console.log("mutant " + m.id + ": " + m.what);
  console.log("  " + m.file + ": " + JSON.stringify(m.find) + " -> " + JSON.stringify(m.replace));
  console.log("  ran test/" + m.test + ": exit " + r.status + ", failing check: " + (failed || "(none)"));
  for (const l of errLines) console.log("    " + l.trim().slice(0, 220));
  if (r.status === 0 || !failed || !m.expect.test(failed)) {
    console.log("  SURVIVED: the test did not fail on the expected check");
    survived++;
  } else console.log("  KILLED");
  fs.rmSync(copy, { recursive: true, force: true });
}
console.log(list.length + " mutants, " + (list.length - survived) + " killed, " + survived + " survived");
process.exit(survived ? 1 : 0);
