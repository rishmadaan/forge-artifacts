// Runnable test: node test/pages.test.js
// The generated pages and the stamps (dark toggle, Markdown export).
const assert = require("node:assert");
const fs = require("node:fs");
const path = require("node:path");
const { check, done, makeStore, makeSrc } = require("./helpers.js");
const core = require("../lib/core.js");
const pages = require("../lib/pages.js");
const workspace = require("../lib/workspace.js");

const BRAND = { name: "Acme", wordmarkSvg: null, indexTagHtml: "Acme &middot; Internal", historyFooterHtml: "Generated by the test publisher." };
const MARK = "data-forge-md-export";
const count = (s, sub) => s.split(sub).length - 1;
function attrOf(html, name) {
  const m = html.match(new RegExp("<div class=\"forge-md\" " + MARK + "[^>]*\\sdata-" + name + "=\"([^\"]*)\""));
  return m && m[1];
}

// Several shared pages with hand-set dates, so index order is testable.
function makeMulti(specs) {
  const ws = workspace.load(makeStore());
  const src = makeSrc();
  for (const sp of specs) {
    core.publish(ws, src.page(sp.file, sp.title, sp.file));
    core.share(ws, core.deriveName(sp.file), "");
  }
  for (const sp of specs) {
    const d = ws.manifest.deliverables[core.deriveName(sp.file)];
    d.versions[d.versions.length - 1].date = sp.date;
  }
  core.saveManifest(ws);
  core.regenerate(ws);
  return ws;
}
function indexTitles(html) {
  return [...html.matchAll(/<a class="title" href="[^"]*">([^<]*)<\/a>/g)].map((x) => x[1]);
}

(async () => {
  await check("index renders newest first on load, title breaks ties, brand prefix stripped", () => {
    const ws = makeMulti([
      { file: "alpha.html", title: "Alpha old page", date: "2026-01-05" },
      { file: "zulu.html", title: "Zulu newest page", date: "2026-10-07" },
      { file: "mike.html", title: "Acme · Mike tie page", date: "2026-08-19" },
      { file: "bravo.html", title: "Bravo tie page", date: "2026-08-19" },
    ]);
    const html = fs.readFileSync(path.join(ws.root, "public", "d", ws.manifest.indexSlug, "index.html"), "utf8");
    assert.deepStrictEqual(indexTitles(html), ["Zulu newest page", "Bravo tie page", "Mike tie page", "Alpha old page"]);
    assert.ok(html.includes('data-sort="recent" aria-pressed="true"'));
    assert.ok(html.indexOf("Last updated in October 2026") < html.indexOf("Last updated in August 2026"));
    assert.ok(html.includes('aria-label="Copy latest link for Zulu newest page"'));
    assert.ok(!/\bautofocus\b/.test(html), "no autofocus attribute (touch keyboards)");
    assert.ok(!/share/i.test(html.replace(/sharing the page/g, "")), "no share counts on the index");
    assert.ok(!/opacity\s*:\s*0(?![.\d])/.test(html), "row actions never hidden");
    assert.ok(!/@keyframes|animation\s*:\s*(?!none)/.test(html), "no entrance animation");
  });

  await check("document toggle is a labelled pill, bottom-right, with reserved space and a print rule", () => {
    const out = pages.injectDarkToggle("<html><body><p>doc</p></body></html>");
    assert.ok(out.includes('aria-label="Switch to dark mode"'));
    assert.ok(/>[^<]*Dark<\/button>/.test(out));
    assert.ok(/#forge-dark-toggle\{[^}]*position:fixed;right:16px;bottom:/.test(out));
    assert.ok(/body\{padding-bottom:/.test(out));
    assert.ok(/@media print\{#forge-dark-toggle\{display:none/.test(out));
    assert.ok(/@media screen\{html\.forge-dark\{filter:/.test(out));
    assert.strictEqual(pages.injectDarkToggle(out), out, "idempotent");
    const idx = pages.renderIndexPage({ items: [], versionsTotal: 0, brand: BRAND });
    assert.ok(idx.includes('class="tpill"') && !idx.includes("forge-dark-toggle-css"));
    assert.ok(idx.includes('<div class="empty"><b>No shared pages yet.</b>Share a page and it will appear here.</div>'), "the empty index's text");
    assert.ok(!/dashboard|Deliverables|forge (share|publish)/i.test(idx), "the static page names no dashboard and no command (the command may be installed as forgee)");
    assert.strictEqual(pages.injectDarkToggle(idx), idx, "a generated page is never stamped");
    const darkDoc = '<html><head><meta name="color-scheme" content="dark"></head><body><p>doc</p></body></html>';
    assert.strictEqual(pages.injectDarkToggle(darkDoc), darkDoc, "dark-authored page is not stamped");
  });

  await check("export block: injected once, idempotent, also on dark-only pages", () => {
    const once = pages.injectMarkdownExport("<html><body><p>doc</p></body></html>", { title: "T", version: 1, date: "2026-10-14", url: "u", slug: "s" });
    assert.strictEqual(count(once, "<div class=\"forge-md\" " + MARK), 1);
    assert.ok(once.indexOf(MARK) < once.lastIndexOf("</body>"));
    assert.strictEqual(pages.injectMarkdownExport(once, { title: "other", version: 9 }), once);
    assert.strictEqual(pages.injectMarkdownExport("<p>no body</p>", null).indexOf("<p>no body</p>"), 0);
    const escaped = pages.injectMarkdownExport("<body></body>", { title: 'A "quoted" <b>&', version: 1 });
    assert.ok(escaped.includes('data-title="A &quot;quoted&quot; &lt;b&gt;&amp;"'));
    const doc = "<html><body><p>The publisher adds data-forge-md-export to its block.</p></body></html>";
    assert.strictEqual(count(pages.injectMarkdownExport(doc, null), '<div class="forge-md" ' + MARK), 1, "a mention is not the block");
  });

  await check("export metadata: title, version, date, public frozen URL, slug and name", () => {
    const ws = workspace.load(makeStore());
    const src = makeSrc();
    const file = src.page("fixture.html", "Fixture Doc", "one");
    const r1 = core.publish(ws, file);
    const v1 = fs.readFileSync(path.join(ws.root, "private", "d", r1.slug, "v1", "index.html"), "utf8");
    assert.strictEqual(attrOf(v1, "title"), "Fixture Doc");
    assert.strictEqual(attrOf(v1, "version"), "1");
    assert.strictEqual(attrOf(v1, "date"), ws.manifest.deliverables.fixture.versions[0].date);
    assert.strictEqual(attrOf(v1, "url"), "https://pub.example.org/d/" + r1.slug + "/v1/");
    assert.strictEqual(attrOf(v1, "slug"), r1.slug);
    assert.strictEqual(attrOf(v1, "name"), "fixture");
  });

  await check("unlabelledDiagrams counts only text-heavy svgs with no aria-label and no direct <title>", () => {
    const t3 = "<text>a</text><text>b</text><text>c</text>";
    assert.strictEqual(pages.unlabelledDiagrams("<svg>" + t3 + "</svg>"), 1);
    assert.strictEqual(pages.unlabelledDiagrams('<svg aria-label="x">' + t3 + "</svg>"), 0);
    assert.strictEqual(pages.unlabelledDiagrams("<svg><title>x</title>" + t3 + "</svg>"), 0);
    assert.strictEqual(pages.unlabelledDiagrams("<svg><text>a</text><text>b</text></svg>"), 0);
    assert.strictEqual(pages.unlabelledDiagrams("<svg><g><title>x</title></g>" + t3 + "</svg>"), 1);
    assert.strictEqual(pages.unlabelledDiagrams('<svg aria-hidden="true">' + t3 + "</svg>"), 0);
  });

  await check("inline-script guard rejects script tags and comment openers, and passes the converter", () => {
    for (const bad of ["a </script> b", "x <!-- y", "<SCRIPT src=x>"]) {
      assert.throws(() => pages.assertScriptSafe(bad), /inline script source/, bad);
    }
    assert.ok(pages.injectMarkdownExport("<body></body>", null).includes("function mdExportMain"));
  });

  await check("the stamps are pinned (hash), so a converter edit is never an accident", () => {
    // The converter is embedded with toString(), comments included: editing
    // ANY line inside mdExportMain, a comment too, changes this hash and makes
    // every page a new version on its next republish. Change it only on
    // purpose. A stamp change makes no new version of a page whose source is
    // unchanged (its recorded source hashes decide), but every imported page
    // (it has none) gets one new version on its next republish. Pinned with
    // the neutral default accent.
    const s = "<html><head><title>Hash pin</title></head><body><p>x</p></body></html>";
    const h = require("node:crypto").createHash("sha256").update(pages.injectMarkdownExport(pages.injectDarkToggle(s), null)).digest("hex");
    assert.strictEqual(h, "6d2d7abf88f3f10f5bf88a9077af897c670d5fb34be3b9a5395513ad3314aaee");
  });

  await check("wordmark: an SVG file is embedded with the brand name; without one the name is text", () => {
    const withSvg = pages.renderVersionsPage({ title: "T", versions: [{ n: 1, date: "2026-01-01" }], brand: { ...BRAND, wordmarkSvg: '<svg viewBox="0 0 1 1"></svg>' } });
    assert.ok(withSvg.includes('<span class="forge-logo" role="img" aria-label="Acme"><svg viewBox="0 0 1 1"></svg></span>'));
    const text = pages.renderVersionsPage({ title: "T", versions: [{ n: 1, date: "2026-01-01" }], brand: BRAND });
    assert.ok(text.includes('<span class="forge-logo">Acme</span>'));
    assert.ok(text.includes("Generated by the test publisher."));
  });

  done();
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
